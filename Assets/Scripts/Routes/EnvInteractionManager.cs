using System;
using System.Collections.Generic;
using System.Linq;
using Unity.Collections;
using Unity.Netcode;
using UnityEngine;

public enum EnvKind : byte
{
    Desk,
    Fan,
    Window,
}

/// <summary>One interactive spot on an existing floor object (a desk, a ceiling fan, a window).</summary>
[Serializable]
public class EnvSpot
{
    public EnvKind kind;
    public Vector3 center;
    public Vector3 size;
    public string label = "";
}

/// <summary>
/// Interactions with the floor model's own furniture, without adding colliders or touching the model:
/// - desks can be searched (some hide route items);
/// - ceiling fans switch on/off and mask the Runner's quiet noises nearby;
/// - windows let the Runner throw something to fake a noise elsewhere.
/// Spots are world boxes generated by RouteSceneBuilder from the current floor model, so they are
/// rebuilt by Tools/Routes/Refresh After Floor Change. Aim is resolved by ray-vs-box.
/// </summary>
public class EnvInteractionManager : NetworkBehaviour
{
    public static EnvInteractionManager Instance { get; private set; }

    [SerializeField] private EnvSpot[] spots = Array.Empty<EnvSpot>();
    [SerializeField, Range(0f, 1f)] private float hideFraction = 0.6f;
    [SerializeField] private float searchSeconds = 1.5f;
    [SerializeField] private float distractHoldSeconds = 1f;
    [SerializeField] private float distractCooldown = 30f;
    [SerializeField] private float fanMaskRadius = 6f;
    [SerializeField] private float interactionRange = 3.6f;
    [Tooltip("Empty desks that can also be searched each round (on top of the ones hiding items).")]
    [SerializeField] private Vector2Int decoyDesks = new(5, 10);

    /// <summary>Desk: 0 searchable, 1 searched empty, 2 searched found, 3 not searchable this round. Fan: 0 off, 1 on.</summary>
    private NetworkList<byte> states;

    public NetworkVariable<double> NextDistractTime = new(0d, NetworkVariableReadPermission.Everyone, NetworkVariableWritePermission.Server);
    public NetworkVariable<int> HiddenCount = new(0, NetworkVariableReadPermission.Everyone, NetworkVariableWritePermission.Server);

    /// <summary>Rooms that still have items inside desks, e.g. "Room1 x1, Laboratory2 x2" (for the item finder).</summary>
    public NetworkVariable<FixedString512Bytes> HiddenRooms = new(default, NetworkVariableReadPermission.Everyone, NetworkVariableWritePermission.Server);

    private readonly Dictionary<int, (string itemId, int count)> contents = new();
    private readonly Dictionary<ulong, (int index, double start, float duration)> holds = new();
    private Target[] targets = Array.Empty<Target>();
    private List<Transform>[] fanBlades;
    private float[] fanSpeed;
    private Vector3[] fanHub;
    private GameObject aimRoot;
    private const int AimLayer = 2; // built-in "Ignore Raycast": other systems' default raycasts skip it

    public IReadOnlyList<EnvSpot> Spots => spots;

    /// <summary>Builder setup.</summary>
    public void Configure(EnvSpot[] newSpots) => spots = newSpots ?? Array.Empty<EnvSpot>();

    private void Awake()
    {
        states = new NetworkList<byte>();
    }

    public override void OnNetworkSpawn()
    {
        Instance = this;
        targets = new Target[spots.Length];
        for (int index = 0; index < spots.Length; index++)
            targets[index] = new Target(this, index);

        if (IsServer && states.Count != spots.Length)
        {
            states.Clear();
            for (int index = 0; index < spots.Length; index++)
                states.Add(0);
        }

        FindFanBlades();
        BuildAimTargets();
    }

    public override void OnNetworkDespawn()
    {
        if (Instance == this)
            Instance = null;
        if (outline != null)
            Destroy(outline.gameObject);
        if (aimRoot != null)
            Destroy(aimRoot);
        aimTargets.Clear();
    }

    private readonly Dictionary<Collider, int> aimTargets = new();

    /// <summary>
    /// Local only: one trigger box per desk and fan on the Ignore Raycast layer, so aiming at them
    /// is a plain raycast against a real collider. Nothing else hits these (default raycasts skip
    /// that layer and character controllers ignore triggers).
    /// </summary>
    private void BuildAimTargets()
    {
        if (aimRoot != null)
            Destroy(aimRoot);
        aimTargets.Clear();

        aimRoot = new GameObject("Env Aim Targets") { layer = AimLayer };
        for (int index = 0; index < spots.Length; index++)
        {
            EnvSpot spot = spots[index];
            if (spot.kind == EnvKind.Window)
                continue;

            GameObject box = new($"Aim {spot.kind} {index}") { layer = AimLayer };
            box.transform.SetParent(aimRoot.transform, false);
            box.transform.position = spot.center;
            BoxCollider collider = box.AddComponent<BoxCollider>();
            collider.isTrigger = true;
            // A little taller than the desk so the top edge is easy to catch from a standing view.
            collider.size = spot.kind == EnvKind.Desk ? spot.size + new Vector3(0.06f, 0.12f, 0.06f) : spot.size + Vector3.one * 0.1f;
            aimTargets[collider] = index;
        }
    }

    /// <summary>
    /// Desk/fan under the crosshair via the aim triggers. Solid things in front only block when they
    /// are wall-like (tall, or a floor/ceiling slab); railings, chairs and the desk's own collision
    /// box do not.
    /// </summary>
    private bool TryFindAimedByCollider(Ray ray, float maxDistance, NetworkPlayerController player, out Target found)
    {
        found = null;
        RaycastHit[] hits = Physics.RaycastAll(ray, maxDistance, 1 << AimLayer, QueryTriggerInteraction.Collide);
        if (hits.Length == 0)
            return false;

        Array.Sort(hits, (a, b) => a.distance.CompareTo(b.distance));
        foreach (RaycastHit hit in hits)
        {
            if (!aimTargets.TryGetValue(hit.collider, out int index) || index >= targets.Length)
                continue;
            if (string.IsNullOrEmpty(PromptFor(index, player)))
                continue;
            if (IsBlocked(ray, hit.distance, spots[index], player))
                return false;

            found = targets[index];
            return true;
        }

        return false;
    }

    private static bool IsBlocked(Ray ray, float distance, EnvSpot spot, NetworkPlayerController player)
    {
        Bounds own = new(spot.center, spot.size + Vector3.one * 0.3f);
        RaycastHit[] solids = Physics.RaycastAll(ray, distance, Physics.DefaultRaycastLayers, QueryTriggerInteraction.Ignore);
        foreach (RaycastHit solid in solids)
        {
            if (solid.distance >= distance - 0.02f)
                continue;
            if (player != null && solid.collider.transform.IsChildOf(player.transform))
                continue;

            Bounds bounds = solid.collider.bounds;
            if (bounds.Intersects(own))
                continue; // the desk's own collision box, or something sitting on it

            Vector3 size = bounds.size;
            bool tall = size.y >= 1.5f;
            bool slab = size.y < 0.25f && Mathf.Min(size.x, size.z) > 1.5f;
            if (tall || slab)
                return true;
        }

        return false;
    }

    private byte State(int index) => states != null && index >= 0 && index < states.Count ? states[index] : (byte)0;

    private static double Now => Unity.Netcode.NetworkManager.Singleton != null
        ? Unity.Netcode.NetworkManager.Singleton.ServerTime.Time
        : Time.timeAsDouble;

    // ================================================================ round (server)

    /// <summary>Server only: close every desk, stop every fan, clear hidden items.</summary>
    public void ServerResetRound()
    {
        if (!IsServer)
            return;

        contents.Clear();
        holds.Clear();
        // Desks start closed; the ones that hide an item, plus a few empty decoys
        // (ServerOpenDecoyDesks), become searchable for this round. Fans/windows reset to 0.
        for (int index = 0; index < states.Count; index++)
            states[index] = index < spots.Length && spots[index].kind == EnvKind.Desk ? (byte)3 : (byte)0;
        HiddenCount.Value = 0;
        HiddenRooms.Value = default;
        NextDistractTime.Value = 0d;
    }

    private void ServerUpdateHiddenRooms()
    {
        string summary = string.Join(", ", contents.Keys
            .GroupBy(index => RoomVolume.NameAt(spots[index].center))
            .OrderBy(group => group.Key)
            .Select(group => $"{group.Key} x{group.Count()}"));
        if (summary.Length > 500)
            summary = summary.Substring(0, 500);
        HiddenRooms.Value = summary;
    }

    /// <summary>
    /// Server only: maybe hide an item in a desk in the same room as its planned spot (instead of
    /// spawning a pickup). Returns true when hidden.
    /// </summary>
    public bool ServerTryHide(string itemId, int count, Vector3 plannedPosition)
    {
        if (!IsServer || UnityEngine.Random.value > hideFraction)
            return false;

        string room = RoomVolume.NameAt(plannedPosition);
        List<int> candidates = new();
        for (int index = 0; index < spots.Length; index++)
        {
            EnvSpot spot = spots[index];
            if (spot.kind != EnvKind.Desk || contents.ContainsKey(index))
                continue;
            if (RoomVolume.NameAt(spot.center) != room)
                continue;
            if (Vector3.Distance(Flat(spot.center), Flat(plannedPosition)) > 12f)
                continue;
            candidates.Add(index);
        }

        if (candidates.Count == 0)
            return false;

        int chosen = candidates[UnityEngine.Random.Range(0, candidates.Count)];
        contents[chosen] = (itemId, Mathf.Max(1, count));
        if (chosen < states.Count)
            states[chosen] = 0;
        HiddenCount.Value++;
        ServerUpdateHiddenRooms();
        return true;
    }

    /// <summary>Server only: open a few random empty desks as decoys (call after hiding items).</summary>
    public void ServerOpenDecoyDesks()
    {
        if (!IsServer)
            return;

        List<int> closed = new();
        for (int index = 0; index < spots.Length && index < states.Count; index++)
        {
            if (spots[index].kind == EnvKind.Desk && states[index] == 3)
                closed.Add(index);
        }

        int wanted = UnityEngine.Random.Range(decoyDesks.x, decoyDesks.y + 1);
        for (int picked = 0; picked < wanted && closed.Count > 0; picked++)
        {
            int at = UnityEngine.Random.Range(0, closed.Count);
            states[closed[at]] = 0;
            closed.RemoveAt(at);
        }
    }

    /// <summary>Server only: is a quiet noise at this position drowned out by a running fan?</summary>
    public bool IsMaskedByFan(Vector3 position)
    {
        for (int index = 0; index < spots.Length; index++)
        {
            if (spots[index].kind != EnvKind.Fan || State(index) == 0)
                continue;
            if (Vector3.Distance(Flat(spots[index].center), Flat(position)) <= fanMaskRadius &&
                Mathf.Abs(spots[index].center.y - position.y) < 4f)
                return true;
        }

        return false;
    }

    // ================================================================ aim (clients)

    private Target lastAimed;
    private float lastAimedTime = -10f;

    /// <summary>
    /// Finds the env spot being aimed at, never through a wall:
    /// - desks: the ray crosses the desk's bounding box (in front of any wall);
    /// - windows: the point looked at is inside the window box, or the ray crosses it in front of any wall;
    /// - fans: the ray crosses the fan box (fans usually have no collision).
    /// A target stays for a moment when the aim slips just off its edge, so it does not flicker.
    /// </summary>
    public bool TryFindAimed(Ray ray, float maxDistance, float firstSolid, NetworkPlayerController player,
        NetworkInventory inventory, out INetworkInteractable target)
    {
        target = null;

        // Desks and fans: real trigger colliders.
        if (TryFindAimedByCollider(ray, maxDistance, player, out Target colliderTarget))
            target = colliderTarget;

        // Windows: ray-vs-box against the glass (the point looked at, or just in front of a wall).
        float best = Mathf.Min(maxDistance, firstSolid + 0.15f);
        Vector3? point = !float.IsPositiveInfinity(firstSolid) && firstSolid <= maxDistance ? ray.GetPoint(firstSolid) : null;
        for (int index = 0; target == null && index < spots.Length && index < targets.Length; index++)
        {
            EnvSpot spot = spots[index];
            if (spot.kind != EnvKind.Window)
                continue;

            Bounds bounds = new(spot.center, spot.size + Vector3.one * 0.04f);
            float distance;
            if (point.HasValue && bounds.Contains(point.Value))
                distance = firstSolid;
            else if (!bounds.IntersectRay(ray, out distance) || distance > best)
                continue;

            if (distance > best || string.IsNullOrEmpty(PromptFor(index, player)))
                continue;

            best = Mathf.Min(best, distance);
            target = targets[index];
        }

        if (target != null)
        {
            lastAimed = (Target)target;
            lastAimedTime = Time.time;
            return true;
        }

        // Grace: keep the last target briefly if the ray is still within 15 cm of its box.
        if (lastAimed != null && Time.time - lastAimedTime < 0.35f &&
            !string.IsNullOrEmpty(PromptFor(lastAimed.Index, player)))
        {
            EnvSpot spot = spots[lastAimed.Index];
            Bounds loose = new(spot.center, spot.size + Vector3.one * 0.3f);
            if (loose.IntersectRay(ray, out float distance) && distance <= maxDistance)
            {
                target = lastAimed;
                return true;
            }
        }

        return false;
    }

    private string PromptFor(int index, NetworkPlayerController player)
    {
        if (!IsSpawned || player == null || index < 0 || index >= spots.Length)
            return null;

        EnvSpot spot = spots[index];
        switch (spot.kind)
        {
            case EnvKind.Desk:
                if (player.IsGranny || State(index) == 3)
                    return null;
                return State(index) == 0 ? $"Hold E  Search {spot.label}" : $"{spot.label}: already searched";

            case EnvKind.Fan:
                return State(index) == 0 ? "E  Switch fan on (hides quiet noises nearby)" : "E  Switch fan off";

            case EnvKind.Window:
                if (player.IsGranny)
                    return null;
                double wait = NextDistractTime.Value - Now;
                return wait > 0d
                    ? $"Window: can throw again in {Mathf.CeilToInt((float)wait)} s"
                    : "Hold E  Throw something out (fake a noise for Granny)";
        }

        return null;
    }

    private float HoldFor(int index)
    {
        if (index < 0 || index >= spots.Length)
            return 0f;

        switch (spots[index].kind)
        {
            case EnvKind.Desk: return State(index) == 0 ? searchSeconds : 0f;
            case EnvKind.Window: return NextDistractTime.Value - Now > 0d ? 0f : distractHoldSeconds;
            default: return 0f;
        }
    }

    // ================================================================ focus outline (local)

    private LineRenderer outline;

    /// <summary>
    /// Local only: outlines the desk/fan/window the local player is aiming at (yellow = usable,
    /// grey = already searched or on cooldown), or hides the outline.
    /// </summary>
    public void ShowFocus(INetworkInteractable focused)
    {
        if (focused is not Target target || target.Manager != this)
        {
            if (outline != null)
                outline.enabled = false;
            return;
        }

        if (outline == null)
        {
            GameObject lineObject = new("Env Focus Outline");
            outline = lineObject.AddComponent<LineRenderer>();
            outline.useWorldSpace = true;
            outline.loop = true;
            outline.widthMultiplier = 0.025f;
            outline.numCornerVertices = 2;
            outline.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
            outline.receiveShadows = false;
            Shader unlit = Shader.Find("Sprites/Default");
            if (unlit != null)
                outline.material = new Material(unlit);
        }

        EnvSpot spot = spots[target.Index];
        Bounds b = new(spot.center, spot.size);
        Vector3[] corners;
        if (spot.kind == EnvKind.Window)
        {
            // Rectangle in the window's plane.
            bool thinX = b.size.x < b.size.z;
            float y0 = b.min.y, y1 = b.max.y;
            corners = thinX
                ? new[] { new Vector3(b.center.x, y0, b.min.z), new Vector3(b.center.x, y0, b.max.z), new Vector3(b.center.x, y1, b.max.z), new Vector3(b.center.x, y1, b.min.z) }
                : new[] { new Vector3(b.min.x, y0, b.center.z), new Vector3(b.max.x, y0, b.center.z), new Vector3(b.max.x, y1, b.center.z), new Vector3(b.min.x, y1, b.center.z) };
        }
        else if (spot.kind == EnvKind.Fan)
        {
            float y = b.min.y;
            corners = new[] { new Vector3(b.min.x, y, b.min.z), new Vector3(b.max.x, y, b.min.z), new Vector3(b.max.x, y, b.max.z), new Vector3(b.min.x, y, b.max.z) };
        }
        else
        {
            // Desks: the whole bounding box as a wireframe (one path, some edges drawn twice).
            Vector3 b0 = new(b.min.x, b.min.y, b.min.z), b1 = new(b.max.x, b.min.y, b.min.z);
            Vector3 b2 = new(b.max.x, b.min.y, b.max.z), b3 = new(b.min.x, b.min.y, b.max.z);
            Vector3 t0 = new(b.min.x, b.max.y, b.min.z), t1 = new(b.max.x, b.max.y, b.min.z);
            Vector3 t2 = new(b.max.x, b.max.y, b.max.z), t3 = new(b.min.x, b.max.y, b.max.z);
            corners = new[] { b0, b1, b2, b3, b0, t0, t1, b1, t1, t2, b2, t2, t3, b3, t3, t0 };
        }

        outline.loop = spot.kind != EnvKind.Desk;
        outline.positionCount = corners.Length;
        outline.SetPositions(corners);
        bool usable = target.HoldSeconds > 0f || spot.kind == EnvKind.Fan;
        Color color = usable ? new Color(1f, 0.85f, 0.3f, 0.9f) : new Color(0.6f, 0.6f, 0.6f, 0.6f);
        outline.startColor = color;
        outline.endColor = color;
        outline.enabled = true;
    }

    private sealed class Target : INetworkInteractable
    {
        private readonly EnvInteractionManager manager;
        private readonly int index;
        public EnvInteractionManager Manager => manager;
        public int Index => index;
        private float localStart = -1f;
        private float localDuration;

        public Target(EnvInteractionManager manager, int index)
        {
            this.manager = manager;
            this.index = index;
        }

        public string GetPrompt(NetworkPlayerController player, NetworkInventory inventory) => manager.PromptFor(index, player);
        public float HoldSeconds => manager.HoldFor(index);

        public float GetHoldProgress() =>
            localStart < 0f || localDuration <= 0f ? 0f : Mathf.Clamp01((Time.time - localStart) / localDuration);

        public void BeginInteract()
        {
            localDuration = HoldSeconds;
            localStart = Time.time;
            manager.BeginRpc(index);
        }

        public void CancelInteract()
        {
            localStart = -1f;
            manager.CancelRpc();
        }
    }

    // ================================================================ server

    [Rpc(SendTo.Server, InvokePermission = RpcInvokePermission.Everyone)]
    private void BeginRpc(int index, RpcParams rpcParams = default)
    {
        if (index < 0 || index >= spots.Length)
            return;

        ulong sender = rpcParams.Receive.SenderClientId;
        if (!TryGetPlayer(sender, out NetworkPlayerController player, out _) || !InRange(player, index))
            return;

        EnvSpot spot = spots[index];
        switch (spot.kind)
        {
            case EnvKind.Fan:
                states[index] = (byte)(State(index) == 0 ? 1 : 0);
                break;

            case EnvKind.Desk:
                if (!player.IsGranny && State(index) == 0)
                    holds[sender] = (index, Now, searchSeconds);
                break;

            case EnvKind.Window:
                if (!player.IsGranny && Now >= NextDistractTime.Value)
                    holds[sender] = (index, Now, distractHoldSeconds);
                break;
        }
    }

    [Rpc(SendTo.Server, InvokePermission = RpcInvokePermission.Everyone)]
    private void CancelRpc(RpcParams rpcParams = default)
    {
        holds.Remove(rpcParams.Receive.SenderClientId);
    }

    private void Update()
    {
        if (IsSpawned)
            SpinFans();

        if (!IsServer || holds.Count == 0)
            return;

        foreach (ulong client in holds.Keys.ToArray())
        {
            (int index, double start, float duration) = holds[client];
            if (!TryGetPlayer(client, out NetworkPlayerController player, out NetworkInventory inventory) ||
                player.MovementLocked.Value || !InRange(player, index))
            {
                holds.Remove(client);
                continue;
            }

            if (Now - start < duration)
                continue;

            holds.Remove(client);
            Complete(index, player, inventory);
        }
    }

    private void Complete(int index, NetworkPlayerController player, NetworkInventory inventory)
    {
        EnvSpot spot = spots[index];
        if (spot.kind == EnvKind.Desk && State(index) == 0)
        {
            if (contents.TryGetValue(index, out (string itemId, int count) found) && inventory != null)
            {
                inventory.ServerGive(found.itemId, found.count);
                contents.Remove(index);
                HiddenCount.Value = Mathf.Max(0, HiddenCount.Value - 1);
                ServerUpdateHiddenRooms();
                states[index] = 2;
                ToastRpc($"Found {ItemIds.DisplayName(found.itemId)} in the {spot.label.ToLowerInvariant()}!",
                    RpcTarget.Single(player.OwnerClientId, RpcTargetUse.Temp));
            }
            else
            {
                states[index] = 1;
                ToastRpc("Nothing here.", RpcTarget.Single(player.OwnerClientId, RpcTargetUse.Temp));
            }
        }
        else if (spot.kind == EnvKind.Window && Now >= NextDistractTime.Value)
        {
            NextDistractTime.Value = Now + distractCooldown;
            Vector3 decoy = PickDecoy(spot.center);
            RouteManager.Instance?.ServerMakeNoise(decoy, NoiseLevel.Loud, "Something crashed");
            ToastRpc($"Thrown! Granny heard a crash near {RoomVolume.NameAt(decoy)}.",
                RpcTarget.Single(player.OwnerClientId, RpcTargetUse.Temp));
        }
    }

    /// <summary>A room centre 12-40 m away from the window, so Granny is pulled away from the Runner.</summary>
    private static Vector3 PickDecoy(Vector3 from)
    {
        RoomVolume[] rooms = FindObjectsByType<RoomVolume>(FindObjectsInactive.Exclude);
        List<Vector3> far = rooms
            .Select(room => room.transform.position)
            .Where(center => Vector3.Distance(Flat(center), Flat(from)) is >= 12f and <= 40f)
            .ToList();
        if (far.Count == 0)
            far = rooms.Select(room => room.transform.position).ToList();
        return far.Count > 0 ? far[UnityEngine.Random.Range(0, far.Count)] : from + new Vector3(15f, 0f, 0f);
    }

    [Rpc(SendTo.SpecifiedInParams)]
    private void ToastRpc(FixedString128Bytes text, RpcParams rpcParams)
    {
        RunnerHud.AddToast(text.ToString(), new Color(1f, 0.9f, 0.55f));
    }

    private bool InRange(NetworkPlayerController player, int index)
    {
        Bounds bounds = new(spots[index].center, spots[index].size);
        Vector3 position = player.transform.position;
        return Vector3.Distance(position, bounds.ClosestPoint(position)) <= interactionRange;
    }

    private static bool TryGetPlayer(ulong clientId, out NetworkPlayerController player, out NetworkInventory inventory)
    {
        player = null;
        inventory = null;
        Unity.Netcode.NetworkManager manager = Unity.Netcode.NetworkManager.Singleton;
        if (manager == null || !manager.ConnectedClients.TryGetValue(clientId, out NetworkClient client) || client.PlayerObject == null)
            return false;

        player = client.PlayerObject.GetComponent<NetworkPlayerController>();
        inventory = client.PlayerObject.GetComponent<NetworkInventory>();
        return player != null && player.MatchStarted.Value;
    }

    // ================================================================ fans (every peer)

    private void FindFanBlades()
    {
        fanBlades = new List<Transform>[spots.Length];
        fanSpeed = new float[spots.Length];
        fanHub = new Vector3[spots.Length];
        Renderer[] renderers = null;
        for (int index = 0; index < spots.Length; index++)
        {
            if (spots[index].kind != EnvKind.Fan)
                continue;

            renderers ??= FindObjectsByType<Renderer>(FindObjectsInactive.Exclude);
            List<Renderer> blades = renderers
                .Where(r => r.name.StartsWith("Blades", StringComparison.Ordinal) &&
                            Vector3.Distance(r.bounds.center, spots[index].center) < 0.6f)
                .ToList();
            fanBlades[index] = blades.Select(r => r.transform).ToList();
            fanHub[index] = FindFanHub(spots[index].center, blades, renderers);
        }
    }

    /// <summary>
    /// The point the blades turn around. The blades' bounding-box centre is NOT the hub for a
    /// three-blade fan (the box is lopsided), so prefer the fan's motor housing ("Top") right above,
    /// then the centroid of the blade mesh, and only then the box centre.
    /// </summary>
    private static Vector3 FindFanHub(Vector3 boxCenter, List<Renderer> blades, Renderer[] renderers)
    {
        Renderer housing = renderers
            .Where(r => r.name.StartsWith("Top", StringComparison.Ordinal) &&
                        Vector3.Distance(Flat(r.bounds.center), Flat(boxCenter)) < 0.6f &&
                        Mathf.Abs(r.bounds.center.y - boxCenter.y) < 1.2f &&
                        Mathf.Max(r.bounds.size.x, r.bounds.size.z) < 0.8f)
            .OrderBy(r => Vector3.Distance(r.bounds.center, boxCenter))
            .FirstOrDefault();
        if (housing != null)
            return new Vector3(housing.bounds.center.x, boxCenter.y, housing.bounds.center.z);

        foreach (Renderer blade in blades)
        {
            MeshFilter filter = blade.GetComponent<MeshFilter>();
            Mesh mesh = filter != null ? filter.sharedMesh : null;
            if (mesh == null || !mesh.isReadable || mesh.vertexCount == 0)
                continue;

            Vector3 sum = Vector3.zero;
            Vector3[] vertices = mesh.vertices;
            foreach (Vector3 vertex in vertices)
                sum += vertex;
            Vector3 centroid = blade.transform.TransformPoint(sum / vertices.Length);
            return new Vector3(centroid.x, boxCenter.y, centroid.z);
        }

        return boxCenter;
    }

    private void SpinFans()
    {
        if (fanBlades == null)
            return;

        for (int index = 0; index < spots.Length && index < fanBlades.Length; index++)
        {
            if (fanBlades[index] == null || fanBlades[index].Count == 0)
                continue;

            float target = State(index) == 1 ? 540f : 0f;
            fanSpeed[index] = Mathf.MoveTowards(fanSpeed[index], target, 360f * Time.deltaTime);
            if (fanSpeed[index] <= 0.01f)
                continue;

            foreach (Transform blade in fanBlades[index])
            {
                if (blade != null)
                    blade.RotateAround(fanHub[index], Vector3.up, fanSpeed[index] * Time.deltaTime);
            }
        }
    }

    private static Vector3 Flat(Vector3 value) => new(value.x, 0f, value.z);
